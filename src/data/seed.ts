export function getAgentById(id: string): Agent | undefined {
  return seedAgents.find(a => a.id === id);
}

export function getListingsBySection(section: ListingSection): Listing[] {
  return seedListings.filter(l => l.section === section);
}

export function getListingsByAgent(agentId: string): Listing[] {
  return seedListings.filter(l => l.agentId === agentId);
}

export function searchAgents(query: string): Agent[] {
  const q = query.toLowerCase();
  return seedAgents.filter(a =>
    a.name.toLowerCase().includes(q) ||
    a.bio.toLowerCase().includes(q) ||
    a.skills.some(s => s.name.toLowerCase().includes(q)) ||
    a.categories.some(c => c.toLowerCase().includes(q))
  );
}
