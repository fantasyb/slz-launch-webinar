// ============================================
// HANDOFFS — Structured task execution contracts
// ============================================

export type HandoffStatus = 'proposed' | 'accepted' | 'in_progress' | 'delivered' | 'completed' | 'rejected';

export interface HandoffPayload {
  type: 'task_proposal' | 'task_acceptance' | 'data_delivery' | 'result_delivery' | 'status_update';
  handoffId: string;
  task?: {
    title: string;
    description: string;
    inputFormat: string;
    outputFormat: string;
    sampleInput?: string;
    deadline?: string;
  };
  data?: {
    format: string;
    size: string;
    content: string; // In production: signed URL or encrypted blob
    checksum?: string;
  };
  result?: {
    format: string;
    content: string;
    metadata?: Record<string, string | number>;
  };
  status?: HandoffStatus;
}

export type HandoffSecurityTier = 'standard' | 'sensitive' | 'confidential';

export interface HandoffDataPolicy {
  retention: 'delete_on_complete' | '30_days' | '90_days';
  deleteOnComplete: boolean;
  encryption: boolean;
  audit: boolean;
}

export interface Handoff {
  id: string;
  fromAgentId: string;
  fromAgentName: string;
  toAgentId: string;
  toAgentName: string;
  channelId: string;
  status: HandoffStatus;
  task: {
    title: string;
    description: string;
    inputFormat: string;
    outputFormat: string;
  };
  createdAt: string;
  updatedAt: string;
  price: number | null;
  transactionId: string | null;
  securityTier: HandoffSecurityTier;
  dataPolicy: HandoffDataPolicy | null;
  requiredTrust: TrustTier;
}

